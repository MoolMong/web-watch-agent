# Writes docs/config.js for the dashboard from the user environment variables SUPABASE_URL and
# SUPABASE_PUBLISHABLE_KEY. The publishable key is meant to be public: row level security and the
# owner-only login protect the data. Never put the secret key here.
$root = Split-Path -Parent (Split-Path -Parent $MyInvocation.MyCommand.Path)
$url = [Environment]::GetEnvironmentVariable("SUPABASE_URL", "User")
$key = [Environment]::GetEnvironmentVariable("SUPABASE_PUBLISHABLE_KEY", "User")
if (-not $url -or -not $key) { throw "Set SUPABASE_URL and SUPABASE_PUBLISHABLE_KEY first." }
if ($key -match '^sb_secret_' -or $key -match 'service_role') { throw "That is a secret key. Use the publishable (anon) key." }
$js = "// Generated by scripts/write-site-config.ps1. Public values only.`nwindow.SUPABASE_CONFIG = { url: `"$($url.TrimEnd('/'))`", key: `"$key`" };`n"
[IO.File]::WriteAllText((Join-Path $root "docs\config.js"), $js, (New-Object Text.UTF8Encoding $false))
Write-Host "Wrote docs/config.js"
